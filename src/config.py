@dataclass(frozen=True)
class TablePaths:
    """Where one source table's files live.

    Every table has the same shape on disk::

        data/<dir_name>/raw/<Name>.csv                     immutable input
        data/<dir_name>/interim/open-refine/<Name>_OR.csv  OpenRefine export
        data/<dir_name>/interim/func-<step>/               one per cleaning function
        data/<dir_name>/interim/cleaned/<Name>_cleaned.csv load-ready for SQLite

    `raw/` and `interim/open-refine/` arrive in the shared input zip; everything
    else is regenerated by `python -m src.run_pipeline`.

    There is deliberately no per-table `final/`. Everything this pipeline writes
    is intermediate as far as the project is concerned -- `data/final/` holds the
    SQL workflow's outputs, which are joins across tables.
    """

    key: str        # dict key / python identifier, e.g. "menu_item"
    dir_name: str   # directory on disk, e.g. "menu-item"
    name: str       # CSV basename stem, e.g. "MenuItem"

    @property
    def root(self) -> Path:
        return DATA_DIR / self.dir_name

    @property
    def raw_dir(self) -> Path:
        return self.root / "raw"

    @property
    def interim_dir(self) -> Path:
        return self.root / "interim"

    @property
    def cleaned_dir(self) -> Path:
        return self.interim_dir / "cleaned"

    @property
    def raw_file(self) -> Path:
        return self.raw_dir / f"{self.name}.csv"

    @property
    def or_file(self) -> Path:
        return self.interim_dir / "open-refine" / f"{self.name}_OR.csv"

    @property
    def cleaned_file(self) -> Path:
        """Load-ready CSV: data columns only, no provenance columns.

        The provenance columns exist to explain how a value got there, which is
        a question about this pipeline, not about the data. Carrying them into
        SQLite would put three columns in every staging table that no query
        needs -- they stay in the func-<step>/ snapshots, where they belong.
        """
        return self.cleaned_dir / f"{self.name}_cleaned.csv"

    def func_dir(self, step: str) -> Path:
        """Directory holding one cleaning function's output.

        Returns the path without creating it -- provenance.write_step() owns
        directory creation so that merely referencing a path has no side effect.
        """
        return self.interim_dir / f"func-{step}"


