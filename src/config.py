"""Shared paths and controlled vocabularies for the Team 38 pipeline.

Single source of truth for where files live and what strings mean, so the
cleaning code, the SQL validation, and docs/data-dictionary.md cannot drift
apart. Every reason code here should map to a problem ID in
docs/data-quality-problems.md and a rule in docs/cleaning-rules.md.

This module is deliberately side-effect free: it *declares* paths but never
creates directories. Run directories are created on demand by
provenance.write_step(), so adding a cleaning function needs no bookkeeping
here -- see src/README.md.
"""

