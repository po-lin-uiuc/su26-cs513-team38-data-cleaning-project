# --- Price outliers (S3 step 4.5) ---------------------------------------
# Winsorization: values above the (1 - WINSORIZE_UPPER_LIMIT) quantile are
# capped at that quantile. Rows are never dropped.
#
# RIGHT TAIL ONLY, and the asymmetry is deliberate. The left tail of a menu
# price distribution is legitimate data -- the median item is $0.40 and a $0.05
# coffee is a real price, not an error. Trimming it would inflate exactly the
# cheap menus U1 needs to rank as cheap.
#
# The limit is 0.5% on evidence, not convention. Of the 4,251 items it caps,
# only 28 (0.7%) sit on dollar-denominated menus: the right tail is almost
# entirely foreign-currency prices -- 180,000 on an Italian Lire menu is an
# ordinary price, not a transcription error -- from menus the currency filter
# already excludes from U1.
#
# Measured effect on the U1 metric (average price per menu), by menu price
# quartile, against the alternatives considered:
#
#     limit    threshold   cheapest    Q2     Q3   priciest
#     5.0%            $9      -0.2%  -0.9%  -3.3%   -13.9%
#     1.0%          $110       0.0%   0.0%   0.0%    -0.6%
#     0.5%          $300       0.0%   0.0%   0.0%    -0.1%   <- chosen
#
# A symmetric 3% trim with row removal was rejected: it shifted the priciest
# quartile by -32.0% and the cheapest by +8.7%, compressing the price range
# that U1 exists to measure.
WINSORIZE_UPPER_LIMIT: Final = 0.005

