def log_tag(column: str, operation: str) -> str:
    """Build one log entry: ``name:uppercased``.

    Tags are `<column>:<operation>` so the Step-5 summary can report cells
    changed *per column* -- splitting on LOG_SEPARATOR then on ":" gives both
    dimensions. Counting without splitting gives wrong numbers; see the open
    question in docs/data-dictionary.md.
    """
    return f"{column}:{operation}"


