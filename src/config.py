# --- Dish.name normalization (S3 step 4.2) ------------------------------
# Target charset: uppercase alphanumeric, space, apostrophe, comma.
#
# Order matters. Quotes are normalized first (so a curly apostrophe survives as
# an apostrophe rather than being folded away), then accents are folded, then
# separators become spaces, then "&" becomes a word, then anything still
# disallowed is deleted, then spaces collapse.
DISH_NAME_ALLOWED: Final[frozenset[str]] = frozenset(
    string.ascii_uppercase + string.digits + " ',"
)

# Word boundaries -- deleting these would weld words together, so they become
# spaces. "Pflaumen-Kompott" -> "PFLAUMEN KOMPOTT", not "PFLAUMENKOMPOTT".
DISH_NAME_SEPARATORS: Final = "-/():;[]{}<>|\\_~"

# Read aloud as a word, so expanded rather than dropped. 11,365 occurrences.
DISH_NAME_REPLACEMENTS: Final[dict[str, str]] = {
    "&": " AND ",
}

# Typographic variants folded to their ASCII equivalents before anything else.
DISH_NAME_QUOTE_MAP: Final[dict[str, str]] = {
    "‘": "'", "’": "'",           # single curly quotes
    "“": '"', "”": '"',           # double curly quotes
    "′": "'", "´": "'", "`": "'",  # prime, acute accent, backtick
    "–": "-", "—": "-", "−": "-",  # en/em dash, minus
    " ": " ",                           # non-breaking space
    "…": " ",                           # ellipsis
}

# A name with no salvageable ASCII content after folding -- typically a
# non-Latin script. Marked rather than dropped so the row survives for
# provenance. Affects a small tail of the 10,076 names containing non-ASCII;
# the rest fold cleanly (MEDOC, SOUP A LA CRECY).
DISH_NAME_UNKNOWN: Final = "UNKNOWN"
